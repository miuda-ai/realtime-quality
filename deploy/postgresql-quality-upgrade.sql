-- RustPBX + Wholesale quality policy upgrade (2026-11-11).
-- Run against an existing application database, with the application schema
-- selected in search_path. Stop concurrent application migrations first.
-- Matches add_sip_trunk_register_username, add_quality_inspection,
-- add_quality_policies, and unify_quality_policy_selection.
-- No changes to auth_username, CDR, billing, or PAI metadata.
-- Migration history is intentionally left to the application's migrators;
-- these four migrations can safely re-run after this script.

BEGIN;

ALTER TABLE rustpbx_sip_trunks
    ADD COLUMN IF NOT EXISTS register_username VARCHAR(160) NULL;

ALTER TABLE rustpbx_tenants
    ADD COLUMN IF NOT EXISTS quality_config JSON NULL;

ALTER TABLE wholesale_routing_profile_items
    ADD COLUMN IF NOT EXISTS quality_config JSON NULL;

CREATE TABLE IF NOT EXISTS wholesale_quality_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL UNIQUE,
    config JSON NOT NULL
);

-- Legacy {"disabled":true,...} -> {"policy_id":0,...}.
-- Otherwise remove "disabled", preserving policy_id and other keys.
-- NULL / JSON null / selections without "disabled" remain unchanged.
UPDATE rustpbx_tenants
SET quality_config = (
    CASE WHEN quality_config::jsonb -> 'disabled' = 'true'::jsonb
         THEN (quality_config::jsonb - 'disabled') || '{"policy_id":0}'::jsonb
         ELSE quality_config::jsonb - 'disabled'
    END
)::json
WHERE jsonb_typeof(quality_config::jsonb) = 'object'
  AND quality_config::jsonb ? 'disabled';

UPDATE wholesale_routing_profile_items
SET quality_config = (
    CASE WHEN quality_config::jsonb -> 'disabled' = 'true'::jsonb
         THEN (quality_config::jsonb - 'disabled') || '{"policy_id":0}'::jsonb
         ELSE quality_config::jsonb - 'disabled'
    END
)::json
WHERE jsonb_typeof(quality_config::jsonb) = 'object'
  AND quality_config::jsonb ? 'disabled';

COMMIT;
